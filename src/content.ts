/** الكلمات = المقاطع المفصولة بمسافات أو كسر سطر */
export const words = (text: string): string[] => text.split(/\s+/).filter(Boolean);

/** فهرس أول كلمة تبدأ بالمقطع المعطى (للمزامنة مع كلمة بعينها) */
export const indexOfWord = (text: string, startsWith: string): number => {
  const i = words(text).findIndex((w) => w.startsWith(startsWith));
  if (i < 0) throw new Error(`word not found: ${startsWith}`);
  return i;
};
